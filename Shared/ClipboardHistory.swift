import Foundation

// Adapted from RightButtonExtension's in-memory text history. See ThirdPartyNotices.txt.
struct ClipboardHistoryItem: Identifiable, Equatable {
    let id: UUID
    let text: String
    let date: Date
}

struct ClipboardHistory {
    private(set) var items: [ClipboardHistoryItem] = []
    var maxCount = 100
    var maxItemBytes = 256 * 1024
    var maxTotalBytes = 4 * 1024 * 1024

    @discardableResult
    mutating func insert(_ text: String, at date: Date = Date()) -> Bool {
        let size = text.utf8.count
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              size <= maxItemBytes, size <= maxTotalBytes, maxCount > 0 else { return false }
        let id = items.first(where: { $0.text == text })?.id ?? UUID()
        items.removeAll { $0.text == text }
        items.insert(ClipboardHistoryItem(id: id, text: text, date: date), at: 0)
        var total = items.reduce(0) { $0 + $1.text.utf8.count }
        while items.count > maxCount || total > maxTotalBytes {
            total -= items.removeLast().text.utf8.count
        }
        return true
    }

    mutating func remove(_ id: UUID) { items.removeAll { $0.id == id } }
    mutating func clear() { items.removeAll(keepingCapacity: false) }

    static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type", "com.agilebits.onepassword"
    ]
    static func mayCapture(types: [String]) -> Bool {
        Set(types).isDisjoint(with: excludedTypes)
    }
}

/// Two completed short presses. Any chord, other key or mouse press cancels.
/// Times are monotonic uptime values, never wall-clock dates.
struct LeftShiftDoubleTap {
    var maximumPressDuration: TimeInterval = 0.25
    var maximumGap: TimeInterval = 0.3
    private var pressedAt: TimeInterval?
    private var previousRelease: TimeInterval?

    mutating func reset() { pressedAt = nil; previousRelease = nil }

    mutating func handle(keyCode: Int, isDown: Bool, hasOtherModifiers: Bool, at time: TimeInterval) -> Bool {
        guard keyCode == 56, !hasOtherModifiers else { reset(); return false }
        if isDown {
            if pressedAt != nil { reset(); return false }
            if let previousRelease, time - previousRelease > maximumGap { self.previousRelease = nil }
            pressedAt = time
            return false
        }
        guard let down = pressedAt, time >= down, time - down <= maximumPressDuration else {
            reset(); return false
        }
        pressedAt = nil
        if let previousRelease, down >= previousRelease, down - previousRelease <= maximumGap {
            reset()
            return true
        }
        previousRelease = time
        return false
    }
}

enum PasteBackGuard {
    static func canSend(targetPID: Int32, frontmostPID: Int32?, targetIsAlive: Bool,
                        permission: Bool, expectedChangeCount: Int, currentChangeCount: Int,
                        modifiersAreReleased: Bool) -> Bool {
        targetIsAlive && permission && frontmostPID == targetPID &&
        expectedChangeCount == currentChangeCount && modifiersAreReleased
    }
}

enum ClipboardPanelLayout {
    static let width: CGFloat = 180
    static let rowHeight: CGFloat = 40
    static let rowSpacing: CGFloat = 5
    static let maximumHeight: CGFloat = 291

    static func height(for count: Int) -> CGFloat {
        min(CGFloat(max(0, count)) * rowHeight + CGFloat(max(0, count - 1)) * rowSpacing + 20,
            maximumHeight)
    }

    static func frame(at mouse: CGPoint, visibleFrame screen: CGRect, count: Int) -> CGRect {
        let size = CGSize(width: min(width, screen.width), height: min(height(for: count), screen.height))
        let x = min(max(mouse.x, screen.minX), screen.maxX - size.width)
        var y = mouse.y - size.height - 12
        if y < screen.minY { y = mouse.y + 12 }
        y = min(max(y, screen.minY), screen.maxY - size.height)
        return CGRect(origin: CGPoint(x: x, y: y), size: size)
    }
}
